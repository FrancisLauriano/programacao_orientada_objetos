package Aula07.Universidade;

public class Aula {
    private String nome;
    private int cH;

    public Aula(String nome, int cH){
        this.nome = nome;
        this.cH = cH;
    }

    public String getNome() {
        return nome;
    }

    public void setNome(String nome) {
        this.nome = nome;
    }

    public int getCH() {
        return cH;
    }

    public void setCH(int cH) {
        this.cH = cH;
    }

    
    
}
